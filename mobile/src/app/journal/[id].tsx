import Ionicons from '@expo/vector-icons/Ionicons';
import { router, useLocalSearchParams } from 'expo-router';
import { Share, StyleSheet, View } from 'react-native';

import { AppText } from '@/components/AppText';
import { Appear, EmptyState, SectionLabel } from '@/components/Bits';
import { Button } from '@/components/Button';
import { Card } from '@/components/Card';
import { Header, IconButton } from '@/components/Header';
import { Screen } from '@/components/Screen';
import { amazonUrl, BOOKS, bookshopUrl } from '@/lib/books';
import { confirmDestructive } from '@/lib/dialog';
import { entryAsText } from '@/lib/exporting';
import { feedback } from '@/lib/feedback';
import { openSafely } from '@/lib/links';
import { useAppStore } from '@/store/app-store';
import { useTheme } from '@/theme/ThemeProvider';
import { space } from '@/theme/tokens';

export default function EntryDetail() {
  const t = useTheme();
  const { id } = useLocalSearchParams<{ id: string }>();
  const entry = useAppStore((s) => s.entries.find((e) => e.id === id));
  const deleteEntry = useAppStore((s) => s.deleteEntry);

  if (!entry) {
    return (
      <Screen>
        <Header title="Entry" />
        <EmptyState icon="document-outline" title="Entry not found" body="It may have been deleted." actionLabel="Back to journal" onAction={() => router.replace('/journal')} />
      </Screen>
    );
  }

  const date = new Date(entry.createdAt).toLocaleString(undefined, { dateStyle: 'full', timeStyle: 'short' });
  const abc = [
    { letter: 'A', title: 'What happened', body: entry.activatingEvent, color: t.blue },
    { letter: 'B', title: 'What you thought', body: entry.beliefs, color: t.lavender },
    { letter: 'C', title: 'How it felt', body: entry.consequences, color: t.sage },
  ];

  return (
    <Screen testID="journal-entry">
      <Header
        title="Reflection"
        right={
          <IconButton
            icon="share-outline"
            label="Share or export this entry"
            onPress={() => Share.share({ message: entryAsText(entry) }).catch(() => {})}
          />
        }
      />
      <AppText variant="caption" tone="muted">
        {date}
      </AppText>

      <Appear>
        <Card tone="lavender" testID="entry-synopsis">
          <AppText variant="label" tone="muted">
            {entry.aiGenerated ? '✨ AI-GENERATED REFLECTION' : 'A GENTLE REMINDER'}
          </AppText>
          <AppText variant="bodyStrong" style={{ marginTop: space.sm }}>
            {entry.synopsis}
          </AppText>
          <AppText variant="caption" tone="muted" style={{ marginTop: space.sm }} testID="ai-disclosure">
            {entry.aiGenerated
              ? 'Generated by AI (Google Gemini). It can be wrong and isn’t professional advice.'
              : 'AI reflections were off or unavailable, so these are reflection prompts. Your entry stayed on this device.'}
          </AppText>
        </Card>
      </Appear>

      <SectionLabel>{entry.aiGenerated ? 'The CBT ABC model' : 'Reflect with the CBT ABC model'}</SectionLabel>
      {abc.map((item, i) => (
        <Appear key={item.letter} index={i + 1}>
          <Card>
            <View style={styles.abcRow}>
              <View style={[styles.letter, { backgroundColor: item.color }]}>
                <AppText variant="heading" tone="onAccent">
                  {item.letter}
                </AppText>
              </View>
              <View style={{ flex: 1, gap: space.xs }}>
                <AppText variant="bodyStrong">{item.title}</AppText>
                <AppText variant="caption" tone="secondary">
                  {item.body}
                </AppText>
              </View>
            </View>
          </Card>
        </Appear>
      ))}

      <SectionLabel>In your words</SectionLabel>
      <Card>
        <AppText selectable>{entry.text}</AppText>
      </Card>

      <SectionLabel>Further reading</SectionLabel>
      <AppText variant="caption" tone="muted">
        Independent picks. Links open a store search; CalmLoop earns nothing from them.
      </AppText>
      {BOOKS.slice(0, 3).map((b) => (
        <Card key={b.title}>
          <AppText variant="bodyStrong">{b.title}</AppText>
          <AppText variant="caption" tone="secondary">
            {b.author} · {b.blurb}
          </AppText>
          <View style={styles.bookLinks}>
            <Button variant="ghost" icon="open-outline" label="Bookshop" onPress={() => openSafely(bookshopUrl(b), 'No browser available.')} />
            <Button variant="ghost" icon="open-outline" label="Amazon" onPress={() => openSafely(amazonUrl(b), 'No browser available.')} />
          </View>
        </Card>
      ))}

      <Button
        variant="ghost"
        label="Delete this entry"
        icon="trash-outline"
        feedbackKind="none"
        onPress={() => {
          feedback.warning();
          confirmDestructive('Delete this entry?', 'This can’t be undone.', 'Delete', () => {
            deleteEntry(entry.id);
            router.back();
          });
        }}
      />
      <View style={styles.footnote}>
        <Ionicons name="lock-closed-outline" size={14} color={t.textMuted} />
        <AppText variant="caption" tone="muted">
          Stored only on this device.
        </AppText>
      </View>
    </Screen>
  );
}

const styles = StyleSheet.create({
  abcRow: { flexDirection: 'row', gap: space.md },
  letter: { width: 40, height: 40, borderRadius: 20, alignItems: 'center', justifyContent: 'center' },
  bookLinks: { flexDirection: 'row', gap: space.sm, marginTop: space.xs },
  footnote: { flexDirection: 'row', gap: space.xs, alignItems: 'center', justifyContent: 'center' },
});
